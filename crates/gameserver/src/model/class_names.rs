//! Java `enums/ClassId` names — the spelling the datapack uses wherever it
//! names a class (`<classId>WARCRYER</classId>`), against the numeric id the
//! rest of the port carries on `Player.class_id`.

/// `ClassId.valueOf(name).getId()`. The enum carries the later-chronicle
/// classes too (the skill data names them); `None` is a name it lacks.
pub fn class_id_by_name(name: &str) -> Option<i32> {
    CLASS_IDS
        .iter()
        .find(|(n, _)| *n == name)
        .map(|&(_, id)| id)
}

